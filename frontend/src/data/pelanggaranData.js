export const getKategoriPelanggaran = (poin) => {
  const p = Number(poin);
  if (p <= 5)
    return {
      label: "Ringan",
      color: "emerald",
      badge: "bg-emerald-100 text-emerald-800 border-emerald-200",
    };
  if (p <= 25)
    return {
      label: "Sedang",
      color: "amber",
      badge: "bg-amber-100 text-amber-800 border-amber-200",
    };
  if (p <= 50)
    return {
      label: "Berat",
      color: "orange",
      badge: "bg-orange-100 text-orange-800 border-orange-200",
    };
  return {
    label: "Sangat Berat",
    color: "rose",
    badge: "bg-rose-100 text-rose-800 border-rose-200",
  };
};

export const getStatusPembinaan = (totalPoin) => {
  const p = Number(totalPoin) || 0;
  if (p >= 75) {
    return {
      status: "SP / Rapat Pleno",
      color: "rose",
      badge: "bg-rose-100 text-rose-800 border-rose-200",
      desc: "Perlu penanganan khusus kepala sekolah, wali kelas & BK",
    };
  }
  if (p >= 50) {
    return {
      status: "Panggilan Orang Tua / BK",
      color: "orange",
      badge: "bg-orange-100 text-orange-800 border-orange-200",
      desc: "Wajib pemanggilan orang tua dan bimbingan konseling",
    };
  }
  if (p >= 25) {
    return {
      status: "Peringatan Wali Kelas",
      color: "amber",
      badge: "bg-amber-100 text-amber-800 border-amber-200",
      desc: "Peringatan tahap awal oleh wali kelas & guru piket",
    };
  }
  return {
    status: "Baik",
    color: "emerald",
    badge: "bg-emerald-100 text-emerald-800 border-emerald-200",
    desc: "Tingkat kedisiplinan baik",
  };
};
